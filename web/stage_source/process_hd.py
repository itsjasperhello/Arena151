# HD arena art: each image is stored at 2400 px wide (2 HD pixels per pixel of the 1200-wide
# layout used for all region coordinates) and painted straight onto the screen.
from PIL import Image, ImageFilter
import numpy as np, cv2, json, base64, io
U = 2.0                                   # HD pixels per layout pixel (layout = 1200 x 896)
UP = '/mnt/user-data/uploads/'
SRC = {   # best available source for each arena, battle floor rectangle in layout pixels
  'plaza':   (UP + '1792411223600_Metro_Plaza.jpeg',     (405, 360, 795, 595)),
  'skyfort': (UP + '1792367621571.jpg',                  (420, 360, 785, 565)),
  'grotto':  (UP + '1792367625400.jpg',                  (458, 392, 748, 545)),
  'oasis':   (UP + '1792367629278.jpg',                  (395, 352, 810, 570)),
  'ruins':   (UP + '1792370622300.jpg',                  (398, 355, 808, 565)),
  'glacier': (UP + '1792411223603_Ice_Island.jpeg',      (398, 352, 808, 558)),
  'cyber':   (UP + '1792411223604_Cyberpoke_Future.jpeg',(398, 355, 808, 562)),
}
imgs, meta = {}, {}
for sid, (path, (x0, y0, x1, y1)) in SRC.items():
    src = Image.open(path).convert('RGB'); w0 = src.width
    hd = src.resize((2400, 1792), Image.LANCZOS)
    if w0 < 2000: hd = hd.filter(ImageFilter.UnsharpMask(radius=1.6, percent=70, threshold=2))   # upscaled sources get a gentle re-sharpen
    if sid == 'skyfort':   # remove the two trainers painted on the side pads; the game draws its own there
        a = np.array(hd)[:, :, ::-1].copy(); m = np.zeros(a.shape[:2], np.uint8)
        for (px0, py0, px1, py1) in [(366, 424, 396, 474), (806, 424, 838, 474)]: m[int(py0*U):int(py1*U), int(px0*U):int(px1*U)] = 255
        hd = Image.fromarray(cv2.inpaint(a, m, 7, cv2.INPAINT_TELEA)[:, :, ::-1])
    buf = io.BytesIO(); hd.save(buf, 'WEBP', quality=84, method=6)
    imgs[sid] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    cx, cy, s = (x0 + x1) / 2, (y0 + y1) / 2, 440 / (x1 - x0)          # s: game art pixels per layout pixel
    meta[sid] = {'cx': cx, 'cy': cy, 's': s, 'U': U, 'l': cx * s - 350, 't': cy * s - 220, 'W': round(1200 * s), 'H': round(896 * s)}
    hd.save(f'/home/claude/stageimg/hd_{sid}.webp', quality=84)
    print(sid, 'source', w0, 'px | webp KB', len(buf.getvalue()) // 1024, '| scale %.3f' % s)
js = '/* HD arena art (2400 px wide) generated by stage_source/process_hd.py. Region coordinates use a 1200 x 896 layout. */\nconst STAGE_IMG = ' + json.dumps(imgs) + ';\nconst STAGE_MAP = ' + json.dumps(meta) + ';\n'
open('/home/claude/m7/src/stage_images.js', 'w').write(js); print('stage_images.js MB %.1f' % (len(js) / 1048576))
